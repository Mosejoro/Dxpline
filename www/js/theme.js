function loadThemePreference() {
  const p = loadProfile(); // from profile-shared.js
  return p.theme && THEME_OPTIONS[p.theme] ? p.theme : "default";
}

// Applies to THIS document's root only — index.html and profile.html each
// call this for themselves since they're separate documents (iframe).
function applyTheme(key) {
  const opt = THEME_OPTIONS[key] || THEME_OPTIONS.default;
  const root = document.documentElement.style;
  if (opt.vars) {
    THEME_VAR_KEYS.forEach((k) => root.setProperty(k, opt.vars[k]));
  } else {
    THEME_VAR_KEYS.forEach((k) => root.removeProperty(k));
  }
}

// Exposed so profile.html (iframe) can persist + push into the parent doc too.
function setThemePreference(key) {
  saveProfile({ theme: key }); // from profile-shared.js
  applyTheme(key);
}

document.addEventListener("DOMContentLoaded", () => {
  applyTheme(loadThemePreference());
});